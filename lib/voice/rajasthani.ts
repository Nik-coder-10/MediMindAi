export function toRajasthani(text: string): string {
  if (!text) return "";
  const trimmed = text.trim();
  if (RAJASTHANI_SPECIFIC_MAP[trimmed]) {
    return RAJASTHANI_SPECIFIC_MAP[trimmed];
  }
  let converted = text;
  for (const [regex, repl] of PHRASE_REPLACEMENTS) {
    converted = converted.replace(regex, repl);
  }
  return converted;
}
